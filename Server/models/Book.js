const mongoose = require("mongoose");

const bookSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: true,
    },

    author: {
      type: String,
      required: true,
    },

    description: {
      type: String,
      required: true,
    },

    price: {
      type: Number,
      required: true,
    },

    category: {
      type: String,
      required: true,
    },

    image: {
      type: String,
      required: true,
    },

    stock: {
      type: Number,
      default: 0,
    },

    language: {
      type: String,
      enum: ["English", "Telugu"],
      default: "English",
    },
  },
  {
    timestamps: true,
    collection: "Books",
  }
);

module.exports = mongoose.model("Book", bookSchema);